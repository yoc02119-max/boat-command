'use strict';
const assert=require('node:assert/strict');
const {allocate}=require('./lab-stake-allocation-v1.js');
const picks=['1-2-3','1-2-4','1-2-5','1-2-6','1-3-2','1-3-4','1-3-5','1-3-6'];
const odds=Object.fromEntries(picks.map(x=>[x,10]));
const ok=allocate({picks,odds,budgetYen:2400});
assert.equal(ok.status,'FEASIBLE');
assert.equal(ok.entries.length,8);
assert.equal(ok.entries.reduce((n,x)=>n+x.stakeYen,0),2400);
assert(ok.entries.every(x=>x.stakeYen%100===0&&x.bufferedProfitYen>0));
assert.equal(allocate({picks,odds:Object.fromEntries(picks.map(x=>[x,5])),budgetYen:2400}).status,'NOT_FEASIBLE');
assert.equal(allocate({picks,odds:{},budgetYen:2400}).reason,'MISSING_OR_INVALID_ODDS');
assert.equal(allocate({picks,odds,budgetYen:700}).reason,'INSUFFICIENT_BUDGET');
const mixed=allocate({picks,odds:{...odds,[picks[0]]:2},budgetYen:2400});
assert.equal(mixed.entries.reduce((n,x)=>n+x.stakeYen,0),2400);
assert(mixed.entries[0].stakeYen>mixed.entries[1].stakeYen);
assert.throws(()=>allocate({picks:[picks[0],picks[0]],odds,budgetYen:800}),/INVALID_PICKS/);
assert.throws(()=>allocate({picks,odds,budgetYen:2450}),/INVALID_BUDGET/);
console.log('LAB stake allocation tests: PASS');
